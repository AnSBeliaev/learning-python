# Числа, строки и кортежи неизменяемые.
# Сложение числа с единицей, дописывание буквы к строке и присоединение элемента
# к кортежу не трогают старый объект. Получается новый, и имя начинает указывать
# на него, поэтому id другой.
# Записать значение в уже существующую позицию строки или кортежа нельзя:
# будет TypeError, объект не поддерживает присваивание по индексу.
# Списки, словари и множества изменяемые.
# Добавление элемента в конец списка, запись нового ключа в словарь и добавление
# элемента в множество меняют тот же объект, id остаётся прежним.

n = 1
print("int", id(n))
n = n + 1
print("int", id(n), n)

s = "ab"
print("str", id(s))
s = s + "c"
print("str", id(s), s)

t = (1, 2)
print("tuple", id(t))
t = t + (3,)
print("tuple", id(t), t)

a = [1, 2]
print("list", id(a))
a.append(3)
print("list", id(a), a)

d = {"x": 1}
print("dict", id(d))
d["y"] = 2
print("dict", id(d), d)

st = {1}
print("set", id(st))
st.add(2)
print("set", id(st), st)
