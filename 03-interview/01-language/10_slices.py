# [0] — элемент с индексом 0.
# [-1] — последний элемент. Отрицательный индекс считает с конца.
# [1:4] — кусок с индекса 1 включительно до 4 не включая его, то есть по индекс 3.
# [:3] — с начала, с индекса 0, до 3 не включая его.
# [::2] — с индекса 0, шаг 2: каждый второй элемент, один между ними пропускается.
# [::-1] — шаг -1: идти справа налево и брать каждый элемент.
# Для строки и списка правила одни. Строка даёт строку, список даёт список.

text = "python"
nums = [10, 20, 30, 40, 50]

for value in (text, nums):
    print(value[0])
    print(value[-1])
    print(value[1:4])
    print(value[:3])
    print(value[::2])
    print(value[::-1])
    print("---")
