# == сравнивает значения. is сравнивает, один ли это объект в памяти.
# CPython заранее создаёт целые числа от -5 до 1024 и выдаёт их повторно.
# Поэтому 1 и 1000 при одинаковом значении оказываются одним объектом, is даёт True.
# 1025 в этот запас не входит. Два отдельно созданных числа равны по значению,
# но это разные объекты, is даёт False.
# Два списка [1] тоже равны по значению и всегда являются разными объектами.
# В одном файле запись a = 1025 и b = 1025 может дать is True: компилятор
# видит обе константы сразу и оставляет один объект. Поэтому число за пределами
# кэша здесь создаётся через int("1025").

a = 1
b = 1
print("1", a == b, a is b)

a = 1000
b = 1000
print("1000", a == b, a is b)

a = int("1025")
b = int("1025")
print("1025", a == b, a is b)

a = [1]
b = [1]
print("list", a == b, a is b)
