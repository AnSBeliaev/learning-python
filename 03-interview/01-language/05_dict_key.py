# Ключ словаря подходит, только если его содержимое нельзя изменить
# ни на одном уровне вложенности.
# Список изменить можно, поэтому он не подходит.
# Кортеж из чисел изменить нельзя, поэтому он подходит.
# Кортеж со списком внутри не подходит: сам кортеж не меняется,
# но список внутри него меняется.

d = {}

try:
    d[[1, 2]] = "list"
except TypeError as error:
    print("list", type(error).__name__, error)

d[(1, 2)] = "tuple"
print("tuple", d[(1, 2)])

try:
    d[(1, [2])] = "inner"
except TypeError as error:
    print("tuple with list", type(error).__name__, error)
