# Присваивание b = a записывает во второе имя ссылку на тот же список.
# Новый список не появляется, поэтому изменение на месте видно через оба имени.
#
# Поверхностная копия создаёт новый внешний список. Внутренние списки остаются
# прежними объектами, ссылки на них те же.
#
# Глубокая копия создаёт и новый внешний список, и новые внутренние объекты.
# Ссылки внутри копии указывают уже на них.

a = [1, 2]
b = a
b.append(3)
print("same object", a)

a = [[1], [2]]
b = a.copy()
b.append([3])
b[0].append(9)
print("shallow", a)

import copy

c = copy.deepcopy(a)
c[0].append(7)
print("deep", a)
print("deep copy", c)
