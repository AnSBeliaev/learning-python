# Словарь в CPython устроен как хеш-таблица.
# По ключу считается число, по нему находится место. В среднем это O(1),
# константное время. Это не обещание для специально подобранного худшего случая.
# Ключи хранятся в порядке добавления, не по алфавиту.
# Замена значения у существующего ключа его место не меняет.
# Ключ подходит, только если содержимое нельзя изменить ни на одном уровне.
# Неизменяемый кортеж подходит. Список и кортеж со списком внутри не подходят.

d = {}
d["c"] = 1
d["a"] = 2
d["b"] = 3
print("order", list(d))

d["a"] = 20
print("after value change", list(d), d["a"])
