# Проверка «элемент уже есть» у списка просматривает элементы по очереди, в среднем O(n).
# Множество в CPython — хеш-таблица без значений, только ключи.
# Проверка in в среднем O(1), как поиск ключа в словаре.
# Повтор не хранится: из [1, 2, 2, 3] во множестве остаётся одна двойка.
# Элемент множества подходит по тем же правилам, что ключ словаря.
# & оставляет общие элементы, | собирает все, - убирает из первого то, что есть во втором.

items = [1, 2, 2, 3]
print("list", 2 in items)
print("set", 2 in set(items), set(items))

a = {1, 2, 3}
b = {3, 4}
print("and", a & b)
print("or", a | b)
print("minus", a - b)
