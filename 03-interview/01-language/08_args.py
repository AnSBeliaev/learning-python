# Звёздочка в объявлении собирает лишние аргументы.
# *args складывает лишние позиционные аргументы в кортеж.
# **kwargs складывает лишние именованные аргументы в словарь.
# Имена args и kwargs — договорённость. Знаки * и ** обязательны.
# При вызове * перед списком раскладывает его в позиционные аргументы.
# ** перед словарём раскладывает его в именованные аргументы.

def show(*args, **kwargs):
    print("positional", args)
    print("named", kwargs)

show(1, 2, name="ann")

numbers = [1, 2]
options = {"name": "ann"}
show(*numbers, **options)
